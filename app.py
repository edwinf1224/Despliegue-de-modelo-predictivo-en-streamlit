Consumidor_habitual = st.selectbox('Consumidor_habitual', ['True', 'False']) # El select box es para que en la interfaz aparezca un recuadro.Fíjese que consumidor habitual ya solo aparece con solo comillas sencillas, pues es un string y en el entrenamiento no estaba entre comillas (mire el bloque de código crear dummies)

# Dataframe. Este Dataframe se crea para que en su interior quede la información que en el paso previo ha introducido el usuario
datos = [[Edad, videojuego,Plataforma,Sexo,Consumidor_habitual]] # Revise que todas las letras de las variables bien sean mayúsculas o minúscuas coincidan con las de los nombres de las variables en la salida data.info() del notebook de entrenamiento, Si no coinciden no funcionará el despliegue
data = pd.DataFrame(datos, columns=['Edad', 'videojuego','Plataforma','Sexo','Consumidor_habitual']) # Dataframe con los mismos nombres de variables

# Se realiza la preparación de datos. Pero antes se hace una copia de los datos:
data_preparada=data.copy()

# Se crean dummies
# En despliegue drop_first= False. En los despliegues no hay necesidad de borrar ninguna dummy

data_preparada = pd.get_dummies(data_preparada, columns=['videojuego', 'Plataforma','Sexo', 'Consumidor_habitual'], drop_first=False, dtype=int)
data_preparada.head()

# Se adicionan las columnas faltantes
# Al método reindex se le mandan los nombres de las variables con las que previamente se entrenó el modelo.
# Ese reindex hace la siguiente comparación: ¿cuáles son las variables con las que yo entrené el modelo? y
# ¿cuáles son las variables con las que se va a realziar la predicción futura? Si hay variables que me sobran
# el método las quita y si hay variables que me faltan las crea y las llena con valores ceros
# En este ejemplo, ninguno de los clientes compró juejo fifa y otros, entonces esos los llenará con ceros
# El reindex me garantiza que concuerden los 2 conjuntos de variables (con las que fueron entrenado el modelo y con las variables futuras que yo voy a utilizar para hacer la predicción futura)

data_preparada=data_preparada.reindex(columns=variables,fill_value=0)
data_preparada.head()

